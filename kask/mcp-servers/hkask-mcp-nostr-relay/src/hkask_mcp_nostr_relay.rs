#![forbid(unsafe_code)]
#![warn(clippy::let_underscore_future)]
//! hkask-mcp-nostr-relay — a loopback Nostr relay that archives the events of
//! authors the operator allowlists.
//!
//! The relay runs for as long as this MCP server process does, which is as
//! long as the editor runs it. It holds no key and signs nothing.
//!
//! Three parts:
//!
//! - [`accept`] — the relay's own HTTP listener. It refuses any request from
//!   a web page before the request becomes a websocket.
//! - [`admission`] — the one rule for what is stored, applied to both the
//!   websocket path and the sync path.
//! - [`server`] — four tools: status, query, sync, and the admission log.
//!
//! Known limit: the listener does not identify callers. Any local process
//! can read the archive, so it holds public events only. The server states
//! this in `nostr_relay_status` and in its NIP-11 document. Design and plan:
//! `kask/docs/research/curator-nostr-relay-design-2026-11-11.md`.

pub mod accept;
pub mod admission;
pub mod config;
pub mod ontology;
pub mod server;
pub mod sync;

// Generated by `build.rs` from the `#[tool]` fn signatures in `src/*.rs`.
// `tool_names_match_live_router` pins the list against the live router.
include!(concat!(env!("OUT_DIR"), "/tool_names.gen.rs"));

pub use server::run;

#[cfg(test)]
mod tool_surface_tests {
    use super::*;

    hkask_mcp_server::tool_surface_pin!(
        crate::server::NostrRelayServer::nostr_relay_router(),
        "nostr_relay_router",
        4,
        tool_surface_is_exactly_4_registered_tools,
    );

    /// Every tool's input schema is strict (no bare boolean in a
    /// schema-valued position), so strict-schema providers accept it.
    #[test]
    fn live_router_schemas_are_strict_for_all_registered_tools() {
        let tools = crate::server::NostrRelayServer::nostr_relay_router().list_all();
        assert_eq!(tools.len(), 4);
        for tool in tools {
            let schema =
                serde_json::to_value(&tool.input_schema).expect("router schema serializes");
            let violations = hkask_types::find_boolean_schema_positions(&schema);
            assert!(
                violations.is_empty(),
                "{} live schema contains bare-boolean positions: {violations:?}",
                tool.name
            );
        }
    }

    /// The panel names this server's tools from `hkask-types` so it need not
    /// link the server. That list must be this server's own.
    #[test]
    fn wire_tool_names_match_the_generated_list() {
        let mut generated: Vec<&str> = TOOL_NAMES.to_vec();
        generated.sort_unstable();
        assert_eq!(generated, hkask_types::nostr_wire::RELAY_TOOL_NAMES);
    }

    /// No tool changes the operator's policy or removes events. A tool added
    /// with such a name fails here and needs a ruling first.
    #[test]
    fn no_tool_writes_policy_or_deletes_events() {
        for name in TOOL_NAMES {
            for verb in [
                "delete", "remove", "allow", "config", "set_", "wipe", "publish",
            ] {
                assert!(
                    !name.contains(verb),
                    "tool {name} looks like a policy or delete verb ({verb})"
                );
            }
        }
    }

    /// The two descriptions a model relies on for safety say what they must:
    /// query output is untrusted text, and sync contacts the network.
    #[test]
    fn descriptions_state_the_trust_and_network_facts() {
        let router = crate::server::NostrRelayServer::nostr_relay_router();
        let description = |name: &str| -> String {
            router
                .list_all()
                .iter()
                .find(|tool| tool.name == name)
                .unwrap_or_else(|| panic!("tool {name} present"))
                .description
                .as_deref()
                .unwrap_or_default()
                .to_string()
        };
        assert!(description("nostr_relay_query").contains("untrusted"));
        assert!(description("nostr_relay_sync").contains("network"));
        assert!(description("nostr_relay_status").contains("access limits"));
    }
}
