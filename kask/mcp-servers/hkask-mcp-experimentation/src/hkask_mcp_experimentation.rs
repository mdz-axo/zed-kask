// ── Registry path (shared by the MCP child and the in-host bridge) ────────

/// Resolve the registry DB path: `HKASK_EXPERIMENTATION_DB` when set to a
/// non-empty value, else the per-agent default under the hKask data dir.
///
/// Both the MCP child (`server::run`) and the in-host health bridge
/// (`kask_bridge::experimentation_health_bridge`) open the registry through this
/// one function — parity is structural, not mirrored: a drift here would
/// read a different registry than the one the tools write.
pub fn registry_path() -> std::path::PathBuf {
    registry_path_from(std::env::var("HKASK_EXPERIMENTATION_DB").ok().as_deref())
}

/// The pure resolution core — testable without process-global env mutation.
pub fn registry_path_from(env_value: Option<&str>) -> std::path::PathBuf {
    match env_value.filter(|value| !value.trim().is_empty()) {
        Some(value) => std::path::PathBuf::from(value),
        None => hkask_types::agent_paths::resolve_under_data_dir(
            &hkask_types::agent_paths::mcp_server_db("experimentation", "experimentation"),
        ),
    }
}

#[cfg(test)]
mod registry_path_tests {
    use super::*;

    /// The parity contract: a non-empty override is honored, and
    /// empty/whitespace/absent all fall to the same per-agent default —
    /// the bridge and the server cannot resolve different registries.
    #[test]
    fn registry_path_override_and_default() {
        let default = registry_path_from(None);
        assert_eq!(default, registry_path_from(Some("")));
        assert_eq!(default, registry_path_from(Some("   ")));
        assert_eq!(
            registry_path_from(Some("/tmp/alt-experimentation.db")),
            std::path::PathBuf::from("/tmp/alt-experimentation.db")
        );
        // The default is the per-agent experimentation registry under the data
        // dir — the same relative path the MCP child serves.
        assert_eq!(
            default,
            hkask_types::agent_paths::resolve_under_data_dir(
                &hkask_types::agent_paths::mcp_server_db("experimentation", "experimentation"),
            )
        );
    }
}

#[cfg(test)]
mod tool_surface_tests {
    use super::*;

    hkask_mcp_server::tool_surface_pin!(
        crate::server::ExperimentationServer::experimentation_router(),
        "experimentation_router",
        8,
        tool_surface_is_exactly_8_registered_tools,
    );

    /// The 2026-10-19 scientific-design evolution (task `f1a90cd2`) added
    /// `design_spec`, `scientific_headroom` and `scientific_outcome`. A tool's
    /// wire schema is generated from its request struct, so those fields are
    /// callable — but the `#[tool(description)]` string is what a model reads
    /// to *discover* them. A description that omits a new parameter is stale
    /// misinformation: the capability exists and is invisible. This pin fails
    /// if the three descriptions stop naming the fields they accept.
    #[test]
    fn tool_descriptions_name_the_scientific_design_fields() {
        let router = crate::server::ExperimentationServer::experimentation_router();
        let description = |name: &str| -> String {
            router
                .list_all()
                .iter()
                .find(|tool| tool.name == name)
                .unwrap_or_else(|| panic!("tool {name} present"))
                .description
                .as_deref()
                .unwrap_or_default()
                .to_string()
        };
        assert!(
            description("experiment_propose").contains("design_spec"),
            "experiment_propose description must name design_spec"
        );
        assert!(
            description("experiment_seal").contains("scientific_headroom"),
            "experiment_seal description must name scientific_headroom"
        );
        assert!(
            description("selection_record").contains("scientific_outcome"),
            "selection_record description must name scientific_outcome"
        );
    }
}
