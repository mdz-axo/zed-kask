#![forbid(unsafe_code)]
#![warn(clippy::let_underscore_future)]
//! hkask-mcp-nostr-client — the agent's instrument for reading Nostr: the
//! identity set in settings, and events from the local relay and the seed
//! relays.
//!
//! This server receives no credential, holds no key and cannot sign. It
//! depends on `hkask-nostr-core` (public operations) and never on
//! `hkask-nostr-signer`: a Nostr key cannot be rotated or recovered, and this
//! process is the one that parses untrusted relay text.
//!
//! Its parts:
//!
//! - [`config`] — the public identity, the seed relays, and where the local
//!   relay announces its listener.
//! - [`relays`] — which addresses are contacted, and what one connection
//!   attempt found.
//! - [`read`] — one question asked of every relay, with each relay's
//!   outcome named and each event's sources kept.
//! - [`identifiers`] and [`thread`] — reading NIP-19 identifiers and
//!   ordering a NIP-10 conversation; neither contacts a relay.
//! - [`server`] — seven tools, all of them reads.
//!
//! Design: `kask/docs/research/curator-nostr-client-design-2026-11-11.md`.

pub mod config;
pub mod identifiers;
pub mod ontology;
pub mod read;
pub mod relays;
pub mod server;
#[cfg(feature = "test-fixture")]
pub mod test_support;
pub mod thread;

// Generated by `build.rs` from the `#[tool]` fn signatures in `src/*.rs`.
// `tool_names_match_live_router` pins the list against the live router.
include!(concat!(env!("OUT_DIR"), "/tool_names.gen.rs"));

pub use server::run;

#[cfg(test)]
mod tool_surface_tests {
    use super::*;

    hkask_mcp_server::tool_surface_pin!(
        crate::server::NostrClientServer::nostr_client_router(),
        "nostr_client_router",
        7,
        tool_surface_is_exactly_7_registered_tools,
    );

    /// The panel names this server's tools from `hkask-types` so it need not
    /// link the server. That list must be this server's own.
    #[test]
    fn wire_tool_names_match_the_generated_list() {
        let mut generated: Vec<&str> = TOOL_NAMES.to_vec();
        generated.sort_unstable();
        assert_eq!(generated, hkask_types::nostr_wire::CLIENT_TOOL_NAMES);
    }

    /// A tool's name says which server it belongs to: `nostr_relay_` is the
    /// relay server's. A client tool named under it would read as a tool
    /// that acts on the local relay.
    #[test]
    fn no_client_tool_is_named_as_a_relay_server_tool() {
        for name in TOOL_NAMES {
            assert!(
                !name.starts_with("nostr_relay_"),
                "tool {name} is named under the relay server's prefix"
            );
            assert!(
                !hkask_types::nostr_wire::RELAY_TOOL_NAMES.contains(name),
                "tool {name} has a relay server tool's name"
            );
        }
    }

    /// Every tool's input schema is strict (no bare boolean in a
    /// schema-valued position), so strict-schema providers accept it.
    #[test]
    fn live_router_schemas_are_strict_for_all_registered_tools() {
        let tools = crate::server::NostrClientServer::nostr_client_router().list_all();
        assert_eq!(tools.len(), 7);
        for tool in tools {
            let schema =
                serde_json::to_value(&tool.input_schema).expect("router schema serializes");
            let violations = hkask_types::find_boolean_schema_positions(&schema);
            assert!(
                violations.is_empty(),
                "{} live schema contains bare-boolean positions: {violations:?}",
                tool.name
            );
        }
    }

    /// No tool of this server signs or publishes. A tool added with such a
    /// name fails here: key custody is an operator decision that has not
    /// been made, and signing belongs to the editor process in any case.
    #[test]
    fn no_tool_is_a_signing_or_publishing_verb() {
        for name in TOOL_NAMES {
            for verb in [
                "sign", "publish", "post", "send", "draft", "react", "repost", "reply", "delete",
                "follow",
            ] {
                assert!(
                    !name.contains(verb),
                    "tool {name} is named as a signing or publishing verb ({verb}); this server only reads"
                );
            }
        }
    }

    /// Every tool that returns text a third party wrote says so, and every
    /// tool that contacts the network says so: a model relies on the
    /// description for both.
    #[test]
    fn descriptions_state_the_trust_and_network_facts() {
        let tools = crate::server::NostrClientServer::nostr_client_router().list_all();
        let description = |name: &str| -> String {
            tools
                .iter()
                .find(|tool| tool.name == name)
                .unwrap_or_else(|| panic!("tool {name} present"))
                .description
                .as_deref()
                .unwrap_or_default()
                .to_string()
        };
        for name in [
            "nostr_fetch_events",
            "nostr_thread",
            "nostr_profile",
            "nostr_author_relays",
            "nostr_notifications",
        ] {
            let text = description(name);
            assert!(text.contains("untrusted text"), "{name}: {text}");
            assert!(text.contains("Contacts the network"), "{name}: {text}");
            assert!(text.contains("Changes nothing"), "{name}: {text}");
        }
        assert!(description("nostr_decode").contains("contacts no relay"));
        assert!(description("nostr_decode").contains("secret key"));
        assert!(description("nostr_account").contains("cannot sign"));
    }
}
