#[cfg(test)]
mod tool_surface_tests {
    use super::*;

    hkask_mcp_server::tool_surface_pin!(
        crate::server::NostrClientServer::nostr_client_router(),
        "nostr_client_router",
        19,
        tool_surface_is_exactly_19_registered_tools,
    );

    /// The panel names this server's tools from `hkask-types` so it need not
    /// link the server. That list must be this server's own.
    #[test]
    fn wire_tool_names_match_the_generated_list() {
        let mut generated: Vec<&str> = TOOL_NAMES.to_vec();
        generated.sort_unstable();
        assert_eq!(generated, hkask_types::nostr_wire::CLIENT_TOOL_NAMES);
    }

    /// A tool's name says which server it belongs to: `nostr_relay_` is the
    /// relay server's. A client tool named under it would read as a tool
    /// that acts on the local relay.
    #[test]
    fn no_client_tool_is_named_as_a_relay_server_tool() {
        for name in TOOL_NAMES {
            assert!(
                !name.starts_with("nostr_relay_"),
                "tool {name} is named under the relay server's prefix"
            );
            assert!(
                !hkask_types::nostr_wire::RELAY_TOOL_NAMES.contains(name),
                "tool {name} has a relay server tool's name"
            );
        }
    }

    /// Every tool's input schema is strict (no bare boolean in a
    /// schema-valued position), so strict-schema providers accept it.
    #[test]
    fn live_router_schemas_are_strict_for_all_registered_tools() {
        let tools = crate::server::NostrClientServer::nostr_client_router().list_all();
        assert_eq!(tools.len(), 19);
        for tool in tools {
            let schema =
                serde_json::to_value(&tool.input_schema).expect("router schema serializes");
            let violations = hkask_types::find_boolean_schema_positions(&schema);
            assert!(
                violations.is_empty(),
                "{} live schema contains bare-boolean positions: {violations:?}",
                tool.name
            );
        }
    }

    /// The publish path is the one ruled writing verb, and it is the only
    /// one. Rulings, verbatim: "when the curator publishes the editor
    /// shows it and the user approves" (2026-11-13); "there should be an
    /// autopublish setting in the nostr settings - and it should be
    /// unselected by default" (2026-11-13); "please proceed" (2026-11-14,
    /// building the publish path). No other tool may sign, publish, post,
    /// send, draft, react, repost, reply, delete or follow: signing
    /// belongs to the editor process, and the operator has not ruled any
    /// other write.
    #[test]
    fn the_only_publishing_verb_is_nostr_publish_note() {
        assert!(
            TOOL_NAMES.contains(&"nostr_publish_note"),
            "the ruled publish path is registered"
        );
        const RULED_WRITING_TOOLS: &[&str] = &[
            "nostr_publish_article",
            "nostr_publish_deletion",
            "nostr_publish_follows",
            "nostr_publish_list",
            "nostr_publish_note",
            "nostr_publish_nutzap",
            "nostr_publish_reaction",
            "nostr_publish_reply",
            "nostr_publish_repost",
        ];
        for name in TOOL_NAMES {
            if RULED_WRITING_TOOLS.contains(name) {
                continue;
            }
            for verb in [
                "sign", "publish", "post", "send", "draft", "react", "repost", "reply", "delete",
                "follow",
            ] {
                assert!(
                    !name.contains(verb),
                    "tool {name} is named as another writing verb ({verb}); only ruled publish paths are allowed"
                );
            }
        }
    }

    /// Every tool that returns text a third party wrote says so, and every
    /// tool that contacts the network says so: a model relies on the
    /// description for both.
    #[test]
    fn descriptions_state_the_trust_and_network_facts() {
        let tools = crate::server::NostrClientServer::nostr_client_router().list_all();
        let description = |name: &str| -> String {
            tools
                .iter()
                .find(|tool| tool.name == name)
                .unwrap_or_else(|| panic!("tool {name} present"))
                .description
                .as_deref()
                .unwrap_or_default()
                .to_string()
        };
        for name in [
            "nostr_fetch_events",
            "nostr_thread",
            "nostr_profile",
            "nostr_author_relays",
            "nostr_notifications",
        ] {
            let text = description(name);
            assert!(text.contains("untrusted text"), "{name}: {text}");
            assert!(text.contains("Contacts the network"), "{name}: {text}");
            assert!(text.contains("Changes nothing"), "{name}: {text}");
        }
        assert!(description("nostr_decode").contains("contacts no relay"));
        assert!(description("nostr_decode").contains("secret key"));
        assert!(description("nostr_account").contains("cannot sign"));
        let publish = description("nostr_publish_note");
        assert!(publish.contains("Contacts the network"), "{publish}");
        assert!(publish.contains("untrusted"), "{publish}");
        assert!(publish.contains("the operator's approval"), "{publish}");
        assert!(publish.contains("autopublish"), "{publish}");
        assert!(publish.contains("read back by id"), "{publish}");

        for blossom_tool in ["nostr_blossom_archive", "nostr_blossom_mirror"] {
            let desc = description(blossom_tool);
            assert!(
                desc.contains("Contacts the network"),
                "{blossom_tool}: {desc}"
            );
            assert!(desc.contains("untrusted"), "{blossom_tool}: {desc}");
            assert!(
                desc.contains("the operator's approval"),
                "{blossom_tool}: {desc}"
            );
            assert!(desc.contains("autopublish"), "{blossom_tool}: {desc}");
        }
    }
}
