fn parse_board_id(board_id: &str) -> Result<hkask_types::BoardId, McpToolError> {
    board_id
        .parse::<hkask_types::BoardId>()
        .map_err(|e| McpToolError::invalid_argument(format!("invalid board_id: {e}")))
}

/// Parse a goal id string or return an `invalid_argument` MCP error.
fn parse_goal_id(goal_id: &str) -> Result<hkask_types::GoalID, McpToolError> {
    goal_id
        .parse::<hkask_types::GoalID>()
        .map_err(|e| McpToolError::invalid_argument(format!("invalid goal_id: {e}")))
}

/// Parse a goal verdict string ("done" | "continue" | "blocked") into a
/// `GoalVerdictValue`.
fn parse_goal_verdict(verdict: &str) -> Result<GoalVerdictValue, McpToolError> {
    // Closed-vocab normalization (operator ruling 2026-10-13): padded or
    // quoted values resolve instead of burning a retry.
    match hkask_types::normalize_closed_vocab(verdict)
        .to_lowercase()
        .as_str()
    {
        "done" => Ok(GoalVerdictValue::Done),
        "continue" => Ok(GoalVerdictValue::Continue),
        "blocked" => Ok(GoalVerdictValue::Blocked),
        other => Err(McpToolError::invalid_argument(format!(
            "invalid verdict {other:?} — expected \"done\", \"continue\", or \"blocked\""
        ))),
    }
}

/// Map a service-layer `KanbanError` to the correct `McpToolError` variant.
///
/// Each `KanbanError` variant maps to a semantically appropriate MCP error kind
/// so that callers can distinguish not-found, permission-denied, precondition
/// failures, and internal errors from simple invalid-input errors.
///
/// contract: kanban-error-mapping
/// expect: "I can distinguish not-found, permission, and workflow errors from invalid-input errors" \[P4\]
/// pre:  e is a valid KanbanError
/// post: returns McpToolError with appropriate McpErrorKind
fn map_kanban_error(e: KanbanError) -> McpToolError {
    match e {
        KanbanError::NotFound(nf) => McpToolError::not_found(nf.to_string()),
        KanbanError::InvalidInput(msg) => McpToolError::invalid_argument(msg),
        KanbanError::InvalidTransition { .. } => McpToolError::failed_precondition(e.to_string()),
        KanbanError::PermissionDenied(msg) => McpToolError::permission_denied(msg),
        KanbanError::WipLimitExceeded { .. } => McpToolError::failed_precondition(e.to_string()),
        KanbanError::Internal(msg) => McpToolError::internal(msg),
    }
}

/// Shape one service call's result into a serialized MCP response: `Ok`
/// maps through `build` and serializes (a serialization failure is an
/// internal error), `Err` maps through `map_kanban_error`. The response
/// construction is the caller's — each tool's response shape is its own
/// contract; the match/serialize/error-mapping tail is shared.
fn respond<T, R: serde::Serialize>(
    result: Result<T, KanbanError>,
    build: impl FnOnce(T) -> R,
) -> Result<serde_json::Value, McpToolError> {
    match result {
        Ok(value) => Ok(serde_json::to_value(build(value))
            .map_err(|e| McpToolError::internal(e.to_string()))?),
        Err(e) => Err(map_kanban_error(e)),
    }
}

/// Map a board's columns into their response form — shared by the board
/// creation and listing tools.
fn column_infos(columns: &[ColumnDef]) -> Vec<ColumnInfo> {
    columns
        .iter()
        .map(|c| ColumnInfo {
            id: c.id.to_string(),
            name: c.name.clone(),
            status: c.status.to_string(),
            wip_limit: c.wip_limit,
        })
        .collect()
}

/// Run the kanban MCP server (used by binary target).
pub async fn run() -> Result<(), hkask_mcp_server::McpError> {
    hkask_mcp_server::run_server(
        hkask_types::kanban_wire::KANBAN_SERVER_NAME,
        env!("CARGO_PKG_VERSION"),
        |ctx: ServerContext| {
            (|| -> anyhow::Result<KanbanServer> {
                // D28 — Standardized Artifact Storage. Default DB path is
                // `{kask_data_dir}/mcp/kata-kanban/kanban.db`, resolved via
                // `resolve_under_data_dir`. Override via `HKASK_KANBAN_DB`.
                // `HKASK_KANBAN_DB` is a non-secret config path — read via
                // `std::env::var` (matching every other DB-path env var:
                // `HKASK_CURATOR_DB`, `HKASK_RESEARCH_DB`, etc.)
                // and injected via `config_env`, not `credentials`.
                let kanban_db_path = std::env::var("HKASK_KANBAN_DB").unwrap_or_else(|_| {
                    let relative_path =
                        hkask_types::agent_paths::mcp_server_db("kata-kanban", "kanban");
                    let default_path =
                        hkask_types::agent_paths::resolve_under_data_dir(&relative_path);
                    if let Some(Err(error)) = default_path.parent().map(std::fs::create_dir_all) {
                        tracing::warn!(
                            target: "hkask.mcp.kata_kanban",
                            path = %default_path.display(),
                            %error,
                            "Failed to create default kanban DB directory \
                             — the subsequent DB open will surface the failure"
                        );
                    }
                    tracing::info!(
                        target: "hkask.mcp.kata_kanban",
                        path = %default_path.display(),
                        "Using default per-agent kanban database"
                    );
                    default_path.to_string_lossy().to_string()
                });
                // Resolve the DB passphrase through the canonical 2-tier chain
                // (ctx.credentials → resolve_credential which does env → keychain).
                // See `hkask_mcp_server::server::resolve_db_passphrase`.
                let passphrase = resolve_db_passphrase(&ctx.credentials)
                    .map_err(|error| anyhow::anyhow!("HKASK_DB_PASSPHRASE: {error}"))?;
                let db = hkask_storage::open_or_repair(&kanban_db_path, &passphrase)
                    .map_err(|error| anyhow::anyhow!("{error}"))?;
                let pool = db
                    .sqlite_pool()
                    .map_err(|error| anyhow::anyhow!("pool: {error}"))?;
                let driver: Arc<dyn hkask_storage::database::driver::DatabaseDriver> =
                    Arc::new(hkask_storage::database::sqlite::SqliteDriver::new_labeled(
                        pool,
                        kanban_db_path.as_str(),
                    ));
                // Clone the handle before `HMemStore` takes ownership: replay
                // protection lives in the same database as the writes it guards.
                let idempotency_driver = driver.clone();
                let store = HMemStore::from_driver(driver)
                    .map_err(|e| anyhow::anyhow!("hmem store init: {e}"))?;
                let service = KanbanService::new(store);

                let worktree_spawn_port = tokio::task::block_in_place(|| {
                    tokio::runtime::Handle::current()
                        .block_on(hkask_inference::resolve_worktree_spawn_port())
                });

                // Replay protection shares the durable encrypted kanban driver.
                // Schema initialization failure aborts startup; accepting writes
                // without durable replay protection would violate the same
                // persistence contract as an unavailable kanban database.
                let idempotency = idempotency::IdempotencyStore::with_driver(idempotency_driver)
                    .map_err(|error| {
                        anyhow::anyhow!("replay-protection schema initialization failed: {error}")
                    })?;

                // Goal replay protection shares the canonical durable store.
                let idempotency = Arc::new(idempotency);
                let goal_idempotency = Arc::clone(&idempotency);

                Ok(KanbanServer::new(
                    ctx.webid,
                    service,
                    worktree_spawn_port,
                    idempotency,
                    goal_idempotency,
                ))
            })()
            .map_err(|e| hkask_mcp_server::McpError::UnexpectedResponse {
                context: "kanban server init".into(),
                detail: e.to_string(),
            })
        },
        vec![hkask_mcp_server::CredentialRequirement::required(
            "HKASK_DB_PASSPHRASE",
            "SQLCipher encryption passphrase (resolved via hkask keystore chain when not set)",
        )],
    )
    .await
}

