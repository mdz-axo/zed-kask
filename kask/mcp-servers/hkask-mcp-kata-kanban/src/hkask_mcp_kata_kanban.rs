    #[tool(
        description = "Update editable fields on a task (title, description, criteria, priority, labels, goal-criterion citations). Only the task owner can edit."
    )]
    pub async fn kanban_task_update(
        &self,
        Parameters(TaskUpdateRequest {
            task_id,
            title,
            description,
            criteria,
            priority,
            labels,
            advances,
        }): Parameters<TaskUpdateRequest>,
    ) -> Result<String, McpToolError> {
        execute_tool(self, "kanban_task_update", async {
            let tid = parse_task_id(&task_id)?;

            // The MCP layer uses single-Option for description and priority:
            // None means "no change," a present value means "set to this."
            // An empty string for description clears the field; an empty
            // string for priority clears the field.
            let description_update = description.map(|d| if d.is_empty() { None } else { Some(d) });
            let priority_update = match priority {
                None => None,
                Some(ref p) if p.is_empty() => Some(None),
                Some(p) => {
                    let parsed = Priority::parse_str(&p).ok_or_else(|| {
                        McpToolError::invalid_argument(format!("invalid priority: {p}"))
                    })?;
                    Some(Some(parsed))
                }
            };

            let criteria_update =
                criteria.map(|cs| cs.into_iter().map(VerificationCriterion::new).collect());

            let advances_update = advances
                .map(|citations| {
                    citations
                        .into_iter()
                        .map(|citation| {
                            Ok::<_, McpToolError>(CriterionCitation {
                                goal_id: parse_goal_id(&citation.goal_id)?,
                                criterion_index: citation.criterion_index,
                                criterion_text: citation.criterion_text,
                            })
                        })
                        .collect::<Result<Vec<_>, _>>()
                })
                .transpose()?;

            respond(
                self.service.task_update(
                    tid,
                    self.webid,
                    title,
                    description_update,
                    criteria_update,
                    priority_update,
                    labels,
                    advances_update,
                ),
                |task| TaskUpdateResponse {
                    task_id: task.id.to_string(),
                    title: task.title,
                    advances_count: task.advances.len(),
                },
            )
        })
        .await
    }

