const SERVER_VERSION: &str = env!("CARGO_PKG_VERSION");

pub async fn run() -> Result<(), hkask_mcp_server::McpError> {
    hkask_mcp_server::run_server(
        "hkask-mcp-swarm",
        SERVER_VERSION,
        |ctx| {
            let mut config = SwarmConfig::from_env();
            // The ONE shared DB passphrase — canonical 2-tier resolution
            // (ctx.credentials → env → keychain), same as every other kask
            // SQLCipher DB opener. On resolution failure the store DEGRADES
            // (memory_unconfigured) — it never falls back open to the
            // source-known DEFAULT_PASSPHRASE; every sibling server fails
            // closed on this state (security-audit run 1, R-01).
            match hkask_mcp_server::server::resolve_db_passphrase(&ctx.credentials) {
                Ok(passphrase) => config.memory_passphrase = passphrase,
                Err(e) => {
                    config.memory_passphrase = String::new();
                    tracing::warn!(
                        target: "hkask.mcp.swarm",
                        error = %e,
                        "HKASK_DB_PASSPHRASE not resolved — the swarm memory store \
                         will degrade (memory_unconfigured); no default fallback"
                    );
                }
            }
            // Surface a missing or too-short DB passphrase so the operator
            // distinguishes "not configured" from "configured but broken"
            // (the .rules startup-failure-signal rule).
            if config.memory_passphrase.is_empty() {
                tracing::warn!(
                    target: "hkask.mcp.swarm",
                    "DB passphrase is empty — local knowledge tools \
                     will degrade. Set HKASK_DB_PASSPHRASE."
                );
            } else if config.memory_passphrase.len() < 8 {
                tracing::warn!(
                    target: "hkask.mcp.swarm",
                    "DB passphrase too short ({} chars — need >=8) — \
                     local knowledge tools will degrade.",
                    config.memory_passphrase.len()
                );
            }
            // Load local agent cards. A missing directory is not an error —
            // the registry stays empty and local tools return zero agents
            // (a loud signal for a misconfigured dir belongs to the operator's
            // log review; the local_swarms load below warns the same way).
            let local_registry =
                std::sync::Arc::new(LocalAgentRegistry::new(config.local_agents_dir.clone()));
            match local_registry.load() {
                Ok(count) => {
                    if count > 0 {
                        tracing::info!(
                            target: "hkask.mcp.swarm",
                            dir = %config.local_agents_dir,
                            count,
                            "loaded local agent cards"
                        );
                    }
                }
                Err(e) => {
                    tracing::warn!(
                        target: "hkask.mcp.swarm",
                        "failed to load local agent cards: {e}"
                    );
                }
            }

            // Construct the local swarm runtime (inference only — there is
            // no local budget; operator ruling 2026-09-04).
            //
            // The runtime is constructed lazily on first tool call (the
            // `run_server` factory closure is sync — it cannot `.await` the
            // inference port resolution). `LazyLocalSwarmRuntime::lazy` stores
            // the operator's selected default model; `get_or_init` does the
            // async init on first use.
            //
            // Per-agent execution stats — the local analog of fermi's
            // `measured_exec_stats`. One store, two handles: the runtime
            // records at the result path, the tools surface it on
            // get/list. Loaded eagerly — a dir scan of tiny JSON files.
            let agent_stats = std::sync::Arc::new(agent_stats::AgentStatsStore::load(
                &config.local_agents_dir,
            ));
            let local_runtime = std::sync::Arc::new(LazyLocalSwarmRuntime::lazy(
                agent_stats.clone(),
                config.default_agent_model.clone(),
            ));

            // The rollout event store (event-substrate data plane). Lazy —
            // opened on first write, so a missing/unwritable path surfaces at
            // the first `swarm_eval_agent_local` call, not at startup. The
            // path contract — the D28 default plus the
            // `HKASK_SWARM_EVENTS_PATH` operator override, shared with zed's
            // harness regression monitor — lives in
            // `hkask_types::agent_paths::swarm_events_db_path`.
            let events_path = hkask_types::agent_paths::swarm_events_db_path();
            let event_store = std::sync::Arc::new(LazyEventStore::lazy(events_path));
            let thread_store = std::sync::Arc::new(thread_store::SwarmThreadStore::new(
                hkask_types::agent_paths::resolve_under_data_dir(
                    &hkask_types::agent_paths::mcp_server_db("swarm", "threads"),
                )
                .to_string_lossy()
                .into_owned(),
                config.memory_passphrase.clone(),
            ));

            // Local swarm registry — the local swarm roster. A missing
            // directory is not an error (created on first
            // `swarm_create_local_swarm`); an empty roster is the normal
            // initial state. Created lazily on first write.
            let local_swarms =
                std::sync::Arc::new(LocalSwarmRegistry::new(config.local_swarms_dir.clone()));
            if let Err(e) = local_swarms.load() {
                tracing::warn!(
                    target: "hkask.mcp.swarm",
                    "local swarms load failed (continuing with empty roster): {e}"
                );
            }

            // Local swarm semantic memory — backs `swarm_search_knowledge_local`
            // (and seeds the generate tools). Lazily opened on first use. The
            // passphrase is the ONE shared DB passphrase (HKASK_DB_PASSPHRASE,
            // resolved from ctx.credentials → env → keychain in `run` above).
            // If the store cannot be opened (e.g., an existing DB was created under a
            // different passphrase), the search tool degrades to an empty result
            // and the generate tools proceed unseeded (memory is an enhancement,
            // not a dependency).
            let local_memory = std::sync::Arc::new(local_knowledge::LazyLocalMemory::lazy(
                config.memory_db_path.clone(),
                config.memory_passphrase.clone(),
                config.embedding_dim,
            ));

            // A2A HTTP gateway (opt-in via HKASK_A2A_HTTP_ENABLE). Exposes local
            // agents to external A2A clients over loopback JSON-RPC. Disabled by
            // default - it opens a loopback port. The startup-failure signals
            // below let an operator distinguish "disabled" from "enabled but
            // broken" (the .rules trap).
            if config.a2a_http_enabled {
                match tokio::runtime::Handle::try_current() {
                    Ok(handle) => match a2a_http::A2aHttpServer::start(
                        local_runtime.clone(),
                        local_registry.clone(),
                        handle,
                    ) {
                        Ok(server) => tracing::info!(
                            target: "hkask.mcp.swarm",
                            port = server.port(),
                            "A2A HTTP gateway enabled on 127.0.0.1:{} (JSON-RPC over POST /)",
                            server.port()
                        ),
                        Err(e) => tracing::warn!(
                            target: "hkask.mcp.swarm",
                            error = %e,
                            "A2A HTTP gateway failed to start - external A2A clients cannot reach                              local agents. Check the loopback port binding."
                        ),
                    },
                    Err(e) => tracing::warn!(
                        target: "hkask.mcp.swarm",
                        error = %e,
                        "A2A HTTP gateway enabled (HKASK_A2A_HTTP_ENABLE=1) but no tokio runtime                          is available - gateway not started"
                    ),
                }
            } else {
                tracing::info!(
                    target: "hkask.mcp.swarm",
                    "A2A HTTP gateway disabled (set HKASK_A2A_HTTP_ENABLE=1 to expose local agents                      to external A2A clients)"
                );
            }

            Ok(SwarmServer::new(
                ctx.webid,
                std::sync::Arc::new(config),
                local_registry,
                local_runtime,
                local_swarms,
                local_memory,
                agent_stats,
                event_store,
                thread_store,
            ))
        },
        vec![],
    )
    .await
}

