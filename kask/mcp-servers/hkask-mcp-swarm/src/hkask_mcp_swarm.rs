    /// expect: "Create and reconfigure report every dropped declared mcp_tools
    /// entry with its reason, and persist the drop report on the card."
    /// Pins the 2026-10-23 observability fix: 12 declared / 9 stored with no
    /// warning read as a capability gap and trained instrument avoidance —
    /// the drop must be visible to the caller, not only in the operator's
    /// log.
    #[tokio::test]
    async fn create_and_reconfigure_report_dropped_mcp_tools() {
        let (server, agents_dir) =
            make_server_in("hkask_mcp_swarm_drop_report", |agents_dir| SwarmConfig {
                local_agents_dir: agents_dir.to_string(),
                allowed_tool_servers: Some(vec!["research".to_string()]),
                ..SwarmConfig::default()
            });

        let created = server
            .swarm_create_local_agent(Parameters(CreateLocalAgentRequest {
                agent_id: "drop_probe".to_string(),
                agent_type: "research".to_string(),
                description: "probe".to_string(),
                system_prompt: "You probe.".to_string(),
                model: String::new(),
                accepts: vec![],
                produces: vec![],
                mcp_tools: vec![
                    "research/web_search".to_string(),
                    "bare_name".to_string(),
                    "host/skill".to_string(),
                    "unknown-server/tool".to_string(),
                ],
                skills: vec![],
                tags: vec![],
                sample_queries: vec![],
                visibility: String::new(),
                valence: None,
                output_contract: None,
                input_contract: None,
                temperature: None,
                model_params: None,
                evaluators: None,
                reasoning: None,
            }))
            .await
            .expect("create ok");
        let created_content = unwrap_content(&created);
        let dropped = created_content["mcp_tools_dropped"]
            .as_array()
            .expect("create result carries the drop report");
        assert_eq!(dropped.len(), 3, "three of four declared entries drop");
        assert_eq!(dropped[0]["tool"], "bare_name");
        assert!(
            dropped[0]["reason"]
                .as_str()
                .unwrap()
                .contains("not server/tool shaped")
        );
        assert_eq!(dropped[1]["tool"], "host/skill");
        assert!(
            dropped[1]["reason"]
                .as_str()
                .unwrap()
                .contains("skills declaration")
        );
        assert_eq!(dropped[2]["tool"], "unknown-server/tool");
        assert!(
            dropped[2]["reason"]
                .as_str()
                .unwrap()
                .contains("governed set")
        );

        let card_path = std::path::Path::new(&agents_dir)
            .join("drop_probe")
            .join("agent_card.json");
        let card: Value =
            serde_json::from_str(&std::fs::read_to_string(&card_path).expect("card written"))
                .expect("card is json");
        assert_eq!(
            card["capabilities"]["mcp_tools"],
            serde_json::json!(["research/web_search"]),
            "only the governed qualified entry is stored"
        );
        assert_eq!(
            card["capabilities"]["dropped_mcp_tools"]
                .as_array()
                .expect("drop report persisted on the card")
                .len(),
            3
        );

        // Reconfigure replaces the declaration — the drop report follows the
        // active list, and the result names the new drops.
        let reconfigured = server
            .swarm_reconfigure_local_agent(Parameters(ReconfigureLocalAgentRequest {
                agent_name: "drop_probe".to_string(),
                system_prompt: "You probe harder.".to_string(),
                model: String::new(),
                mcp_tools: vec![
                    "research/annotate_research_run".to_string(),
                    "host/render_template".to_string(),
                ],
                skills: vec![],
                model_params: None,
            }))
            .await
            .expect("reconfigure ok");
        let reconfigured_content = unwrap_content(&reconfigured);
        let redropped = reconfigured_content["mcp_tools_dropped"]
            .as_array()
            .expect("reconfigure result carries the drop report");
        assert_eq!(redropped.len(), 1);
        assert_eq!(redropped[0]["tool"], "host/render_template");
        assert!(
            redropped[0]["reason"]
                .as_str()
                .unwrap()
                .contains("skills declaration")
        );

        let card: Value =
            serde_json::from_str(&std::fs::read_to_string(&card_path).expect("card reread"))
                .expect("card is json");
        assert_eq!(
            card["capabilities"]["mcp_tools"],
            serde_json::json!(["research/annotate_research_run"])
        );
        assert_eq!(
            card["capabilities"]["dropped_mcp_tools"]
                .as_array()
                .expect("drop report follows the active declaration")
                .len(),
            1
        );
    }
