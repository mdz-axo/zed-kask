//! Build script — generates `tool_names.gen.rs` from `#[tool]` fn signatures.
//!
//! The shared scan/generation/change-detection mechanics live in
//! `hkask-mcp-server/build_support/tool_names.rs`; this driver keeps only the
//! swarm-specific entry point.

#[path = "../../crates/hkask-mcp-server/build_support/tool_names.rs"]
mod tool_names;

fn main() {
    let (src_dir, out_path) = tool_names::src_and_out_paths();

    let mut names = std::collections::BTreeSet::new();
    for source in tool_names::rust_sources(&src_dir, true) {
        tool_names::scan_tool_fns(&source, &mut names);
    }

    let entries = tool_names::entries(&names);
    let generated = format!(
        "// Auto-generated by build.rs — do not edit.\n\
         // Scans `src/**/*.rs` for `#[tool]`-annotated `pub async fn` signatures.\n\
         pub const TOOL_NAMES: &[&str] = &[\n{entries}];\n"
    );

    tool_names::write_if_changed(&out_path, &generated, &src_dir);
}
